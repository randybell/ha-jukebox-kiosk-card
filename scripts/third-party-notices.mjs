// Rollup plugin: writes THIRD_PARTY_NOTICES.md (repo root, and dist/ for the release) listing every npm package
// whose modules ended up in the bundle, with its version, license and full license text from node_modules, plus
// the self-hosted OFL fonts shipped in the release fonts zip. Output is deterministic (sorted, no timestamps).
import { readFileSync, readdirSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, sep } from 'node:path';

// Fonts copied by scripts/copy-fonts.mjs (not part of the JS bundle; shipped in jukebox-card-fonts.zip).
const FONTS = [
  {
    pkg: '@fontsource/inter',
    family: 'Inter',
    authors: 'Rasmus Andersson and The Inter Project Authors',
    project: 'https://github.com/rsms/inter',
    files: 'inter-400/600/700/800.woff2 (Latin subset)',
    licenseFile: 'fonts/LICENSE-Inter.txt',
  },
  {
    pkg: '@fontsource/plus-jakarta-sans',
    family: 'Plus Jakarta Sans',
    authors: 'Gumpita Rahayu (Tokotype) and The Plus Jakarta Sans Project Authors',
    project: 'https://github.com/tokotype/PlusJakartaSans',
    files: 'plus-jakarta-sans-700/800.woff2 (Latin subset)',
    licenseFile: 'fonts/LICENSE-PlusJakartaSans.txt',
  },
];

function packageRoot(id) {
  const marker = `${sep}node_modules${sep}`;
  const i = id.lastIndexOf(marker);
  if (i < 0) return null;
  // Walk up from the module to the nearest package.json that has a name and version.
  let dir = dirname(id);
  while (dir.length > i + marker.length - 1) {
    const pj = join(dir, 'package.json');
    if (existsSync(pj)) {
      const json = JSON.parse(readFileSync(pj, 'utf8'));
      if (json.name && json.version) return { dir, json };
    }
    dir = dirname(dir);
  }
  return null;
}

function licenseText(dir) {
  const f = readdirSync(dir).filter((n) => /^(licen[cs]e|copying)(\.|$)/i.test(n)).sort()[0];
  if (!f) throw new Error(`third-party-notices: no LICENSE file in ${dir}`);
  return readFileSync(join(dir, f), 'utf8').replace(/\s+$/, '');
}

const licenseOf = (json) => (typeof json.license === 'string' ? json.license : json.license?.type) || 'UNKNOWN';
const fence = (text) => '```text\n' + text + '\n```';

export function render(pkgs, fontPkgs, version) {
  const out = [];
  out.push('# Third-party notices');
  out.push('');
  out.push(`Jukebox Card ${version} is MIT licensed (see LICENSE). This file is generated by \`npm run build\``);
  out.push('(scripts/third-party-notices.mjs) and ships with every GitHub release, both as a release asset and');
  out.push('inside jukebox-card-fonts.zip. It covers the third-party code bundled into `jukebox-card.js` and the');
  out.push('fonts shipped in the fonts zip. Their license comments are also kept in the minified bundle.');
  out.push('');
  out.push('## Bundled into jukebox-card.js');
  out.push('');
  out.push('| Package | Version | License |');
  out.push('| --- | --- | --- |');
  for (const p of pkgs) out.push(`| ${p.name} | ${p.version} | ${p.license} |`);
  out.push('');
  for (const p of pkgs) {
    out.push(`### ${p.name} ${p.version}`);
    out.push('');
    out.push(`License: ${p.license}${p.homepage ? `  \nHomepage: ${p.homepage}` : ''}`);
    out.push('');
    out.push(fence(p.text));
    out.push('');
  }
  out.push('## Fonts in jukebox-card-fonts.zip');
  out.push('');
  out.push('The fonts are licensed under the SIL Open Font License 1.1 (OFL-1.1), not MIT. The full OFL text for');
  out.push('each family also ships next to the font files (`fonts/LICENSE-*.txt`). The font files come from the');
  out.push('Fontsource npm packages (https://fontsource.org).');
  out.push('');
  out.push('| Font family | Authors | Files | License | Source package |');
  out.push('| --- | --- | --- | --- | --- |');
  for (const f of fontPkgs) out.push(`| ${f.family} | ${f.authors} (${f.project}) | ${f.files} | ${f.license} | ${f.name} ${f.version} |`);
  out.push('');
  for (const f of fontPkgs) {
    out.push(`### ${f.family} (${f.name} ${f.version})`);
    out.push('');
    out.push(`License: ${f.license} (also shipped as \`${f.licenseFile}\`)`);
    out.push('');
    out.push(fence(f.text));
    out.push('');
  }
  return out.join('\n');
}

export default function thirdPartyNotices({ files = ['THIRD_PARTY_NOTICES.md', 'dist/THIRD_PARTY_NOTICES.md'] } = {}) {
  return {
    name: 'third-party-notices',
    generateBundle() {
      const found = new Map();
      // Every module in the bundle's graph, including pure re-export modules (e.g. lit/index.js) that render no code.
      for (const id of this.getModuleIds()) {
        if (id.startsWith('\0')) continue;
        const info = this.getModuleInfo(id);
        if (!info || info.isExternal) continue;
        const root = packageRoot(id);
        if (!root || found.has(root.json.name)) continue;
        found.set(root.json.name, {
          name: root.json.name,
          version: root.json.version,
          license: licenseOf(root.json),
          homepage: root.json.homepage || '',
          text: licenseText(root.dir),
        });
      }
      const pkgs = [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
      const fontPkgs = FONTS.map((f) => {
        const dir = join('node_modules', f.pkg);
        const json = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
        return { ...f, name: json.name, version: json.version, license: licenseOf(json), text: licenseText(dir) };
      });
      const version = JSON.parse(readFileSync('package.json', 'utf8')).version;
      const md = render(pkgs, fontPkgs, version) + '\n';
      for (const file of files) {
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, md);
      }
      this.info?.(`third-party notices: ${pkgs.map((p) => `${p.name}@${p.version}`).join(', ')}`);
    },
  };
}
